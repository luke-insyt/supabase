// GET-459 — release_due_open_candidates, checked on a real Postgres (PGlite, in-process; no
// Docker, no network, no secrets).
//
// Runs 20261123120000_get459_release_due_open_candidates.sql on a minimal stand-in of the
// tables it joins (purchases, insyts, inquiry_proposals, inquiries) and asserts:
//   - no starvation: 150 unbought open insyts plus one bought one → the bought one comes back
//     with p_limit = 100 (the selection starts from purchases);
//   - a bought timed, exclusive, draft, already-released or public row is never returned;
//   - an n8n twin purchase row (two rows, one checkout) → the insyt once (distinct);
//   - p_limit caps the answer, and the order is stable (by id);
//   - EXECUTE is service_role only;
//   - the migration is idempotent (runs twice).
//
// Run (from the repo root):  deno test -A supabase/tests/get459_release_due_open_candidates_test.ts
// Side-by-side checkout:     DENO_NO_PACKAGE_JSON=1 deno test -A supabase/tests/get459_release_due_open_candidates_test.ts
// No local Deno?             npx -y deno@2.1.4 test -A --node-modules-dir=none supabase/tests/get459_release_due_open_candidates_test.ts
import { assert, assertEquals } from 'jsr:@std/assert@1'
import { PGlite } from 'npm:@electric-sql/pglite@0.2.17'

const migration = await Deno.readTextFile(
  new URL('../migrations/20261123120000_get459_release_due_open_candidates.sql', import.meta.url),
)

// The columns the function reads. No FK from purchases to insyts — as in production.
const STAND_IN = `
create role anon; create role authenticated; create role service_role;
create table public.inquiries (
  id uuid primary key default gen_random_uuid(),
  access_mode text);
create table public.inquiry_proposals (
  id uuid primary key default gen_random_uuid(),
  inquiry_id uuid not null references public.inquiries (id));
create table public.insyts (
  id uuid primary key default gen_random_uuid(),
  insyt_id character varying,
  status character varying default 'live',
  visibility text not null default 'private',
  inquiry_proposal_id uuid,
  release_price_cents integer,
  released_at timestamptz);
create table public.purchases (
  id bigint generated by default as identity primary key,
  insyt_id text,
  stripe_session_id text,
  stripe_blob json);
-- Supabase's default privileges: every NEW function in public is granted to the API roles.
-- Without this the EXECUTE revoke check below could never fail.
alter default privileges in schema public grant execute on functions to anon, authenticated;
`

type Row = { id: string; insyt_id: string }

async function db() {
  const pg = new PGlite()
  await pg.exec(STAND_IN)
  await pg.exec(migration)
  let n = 0
  // One delivered insyt for an inquiry in `mode`; `over` patches the insyt row.
  const insyt = async (mode: string, over: Record<string, unknown> = {}, bought = false) => {
    n++
    const slug = `slug-${String(n).padStart(4, '0')}`
    const q = (await pg.query<{ id: string }>(`insert into public.inquiries (access_mode) values ($1) returning id`, [mode])).rows[0].id
    const p = (await pg.query<{ id: string }>(`insert into public.inquiry_proposals (inquiry_id) values ($1) returning id`, [q])).rows[0].id
    const row = {
      insyt_id: slug,
      status: 'live',
      visibility: 'private',
      inquiry_proposal_id: p,
      release_price_cents: mode === 'open' ? 0 : null,
      released_at: null,
      ...over,
    }
    const cols = Object.keys(row)
    const id = (await pg.query<{ id: string }>(
      `insert into public.insyts (${cols.join(', ')}) values (${cols.map((_, i) => `$${i + 1}`).join(', ')}) returning id`,
      Object.values(row),
    )).rows[0].id
    if (bought) await pg.query(`insert into public.purchases (insyt_id, stripe_session_id) values ($1, $2)`, [slug, `cs_${n}`])
    return { id, insyt_id: slug }
  }
  const candidates = async (limit = 100) =>
    (await pg.query<Row>(`select * from public.release_due_open_candidates($1)`, [limit])).rows
  return { pg, insyt, candidates }
}

Deno.test('no starvation: 150 unbought open insyts + 1 bought → the bought one (p_limit 100)', async () => {
  const { insyt, candidates } = await db()
  for (let i = 0; i < 150; i++) await insyt('open')
  const bought = await insyt('open', {}, true)
  assertEquals(await candidates(100), [bought])
})

Deno.test('a bought timed, exclusive, draft, released or public row is never returned', async () => {
  const { insyt, candidates } = await db()
  await insyt('timed', {}, true)
  await insyt('exclusive', {}, true)
  await insyt('open', { status: 'draft' }, true)
  await insyt('open', { released_at: '2026-11-21T09:00:00Z' }, true)
  await insyt('open', { visibility: 'public' }, true)
  await insyt('open', { release_price_cents: null }, true) // not delivered as free-at-release
  const ok = await insyt('open', { status: 'published' }, true)
  assertEquals(await candidates(), [ok])
})

Deno.test("an n8n twin purchase row (same checkout) → the insyt once", async () => {
  const { pg, insyt, candidates } = await db()
  const bought = await insyt('open', {}, true)
  await pg.query(`insert into public.purchases (insyt_id, stripe_session_id, stripe_blob) values ($1, 'cs_1', '{}')`, [bought.insyt_id])
  assertEquals(await candidates(), [bought])
})

Deno.test('p_limit caps the answer; the order is by id', async () => {
  const { insyt, candidates } = await db()
  const all: Row[] = []
  for (let i = 0; i < 5; i++) all.push(await insyt('open', {}, true))
  const sorted = [...all].sort((a, b) => (a.id < b.id ? -1 : 1))
  assertEquals(await candidates(3), sorted.slice(0, 3))
  assertEquals(await candidates(), sorted)
})

Deno.test('EXECUTE is service_role only', async () => {
  const { pg } = await db()
  const can = async (role: string) =>
    (await pg.query<{ ok: boolean }>(
      `select has_function_privilege($1, 'public.release_due_open_candidates(int)', 'execute') as ok`,
      [role],
    )).rows[0].ok
  assertEquals(await can('anon'), false)
  assertEquals(await can('authenticated'), false)
  assertEquals(await can('service_role'), true)
})

Deno.test('the migration is idempotent', async () => {
  const { pg, insyt, candidates } = await db()
  await pg.exec(migration)
  const bought = await insyt('open', {}, true)
  assert((await candidates()).some((r) => r.id === bought.id))
})
