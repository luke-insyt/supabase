Deno.test('immutability (AC5.4): no update, delete or truncate — owner and service role alike', async () => {
  const f = await db()
  const id = await record(f.pg, { kind: 'claim', amount: 100, rule: '§2', insyt: 'ia' })
  await rejects(f.pg.query(`update public.insyter_deductions set amount_cents = 1 where id = $1`, [id]), 'immutable')
  await rejects(f.pg.query(`update public.insyter_deductions set reason = 'changed' where id = $1`, [id]), 'immutable')
  await rejects(f.pg.query(`delete from public.insyter_deductions where id = $1`, [id]), 'immutable')
  await rejects(f.pg.query(`truncate public.insyter_deductions`), 'immutable')
  // Settle once, then never again (and never re-pointed to another payout).
  const p1 = await payout(f.pg, A, [], [id])
  const p2 = await payout(f.pg, A, [], [])
  await rejects(f.pg.query(`update public.insyter_deductions set settled_payout_id = $2 where id = $1`, [id, p2]), 'immutable')
  await rejects(f.pg.query(`update public.insyter_deductions set settled_payout_id = null, settled_at = null where id = $1`, [id]), 'immutable')
  assertEquals(Number((await listFor(f.pg, A))[0].settled_payout_id), p1)
  // A hold can't be settled even by a direct update.
  const hold = await record(f.pg, { kind: 'hold', amount: 5 })
  await rejects(f.pg.query(`update public.insyter_deductions set settled_payout_id = $2, settled_at = now() where id = $1`, [hold, p2]), 'immutable')
  // The service role has SELECT only: every direct write is refused before the trigger.
  await f.pg.exec('set role service_role')
  try {
    await rejects(
      f.pg.query(`insert into public.insyter_deductions (creator_auth_user_id, kind, amount_cents, reason) values ($1, 'hold', 1, 'x')`, [A]),
      'permission denied',
    )
    await rejects(f.pg.query(`delete from public.insyter_deductions where id = $1`, [id]), 'permission denied')
    assertEquals((await f.pg.query(`select id from public.insyter_deductions`)).rows.length, 2)
  } finally {
    await f.pg.exec('reset role')
  }
})

Deno.test('payout netting (AC5.5): payout, items and settlement in one transaction; status "settled" + payout date', async () => {
  const f = await db()
  const refund = await record(f.pg, { kind: 'refund', amount: 640, purchase: f.pa })
  const claim = await record(f.pg, { kind: 'claim', amount: 200, rule: '§11', insyt: 'ia' })
  const hold = await record(f.pg, { kind: 'hold', amount: 50 })
  const pid = await payout(f.pg, A, [
    { source: 'purchase', purchase_id: f.pa2, stripe_payment_id: null, amount_cents: 2000, currency: 'eur' },
    { source: 'subscription', purchase_id: null, stripe_payment_id: 'in_a', amount_cents: 500, currency: 'eur' },
  ], [refund, refund]) // duplicate ids are fine
  const items = (await f.pg.query(`select * from public.creator_payout_items where payout_id = $1`, [pid])).rows
  assertEquals(items.length, 2)
  const rows = await listFor(f.pg, A)
  const r = rows.find((x) => x.id === refund)!
  assertEquals(r.status, 'settled')
  assertEquals(Number(r.settled_payout_id), pid)
  assert(r.settled_payout_date)
  assertEquals(rows.find((x) => x.id === claim)!.status, 'open')
  // A hold, a settled row, or another creator's row → the WHOLE payout rolls back.
  const before = (await f.pg.query<{ n: number }>(`select count(*)::int as n from public.creator_payouts`)).rows[0].n
  await rejects(payout(f.pg, A, [], [claim, hold]), 'deduction_not_settleable')
  await rejects(payout(f.pg, A, [], [refund]), 'deduction_not_settleable')
  const otherB = await record(f.pg, { creator: B, kind: 'hold', amount: 1 })
  const claimB = await record(f.pg, { creator: B, kind: 'claim', amount: 1, rule: '§2' })
  await rejects(payout(f.pg, A, [], [claimB]), 'deduction_not_settleable')
  await rejects(payout(f.pg, A, [], [crypto.randomUUID()]), 'deduction_not_settleable')
  assertEquals((await f.pg.query<{ n: number }>(`select count(*)::int as n from public.creator_payouts`)).rows[0].n, before)
  assertEquals(rows.find((x) => x.id === claim)!.status, 'open')
  assert(otherB)
  // A double-covered payment is still a 23505 (the server's 409), and rolls back the settlement too.
  const dup = await payout(
    f.pg, A, [{ source: 'purchase', purchase_id: f.pa2, stripe_payment_id: null, amount_cents: 2000, currency: 'eur' }], [claim],
  ).then(() => null, (e: { code?: string }) => e)
  assertEquals(dup?.code, '23505')
  assertEquals((await listFor(f.pg, A)).find((x) => x.id === claim)!.status, 'open')
  // Negative amount refused by the existing check.
  await rejects(payout(f.pg, A, [], [claim], -1), 'creator_payouts_amount_cents_check')
  // A correction settles like a deduction (it adds money back).
  const corr = await record(f.pg, { kind: 'correction', amount: 100, related: claim })
  await payout(f.pg, A, [], [claim, corr], 0)
  const after = await listFor(f.pg, A)
  assertEquals(after.find((x) => x.id === corr)!.status, 'settled')
  assertEquals(after.find((x) => x.id === claim)!.status, 'settled')
})

