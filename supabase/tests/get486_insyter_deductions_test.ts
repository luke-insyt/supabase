Deno.test('holds (AC5.3): held until released; release = same amount, once; the release row shows released', async () => {
  const f = await db()
  const hold = await record(f.pg, { kind: 'hold', amount: 900, insyt: 'ia', reason: 'Claim open' })
  assertEquals((await listFor(f.pg, A))[0].status, 'held')
  await rejects(record(f.pg, { kind: 'hold_released', amount: 800, related: hold }), 'release_amount_mismatch')
  const rel = await record(f.pg, { kind: 'hold_released', amount: 900, related: hold, reason: 'Claim dropped' })
  const rows = await listFor(f.pg, A)
  assertEquals(rows.find((r) => r.id === hold)!.status, 'released')
  const relRow = rows.find((r) => r.id === rel)!
  assertEquals(relRow.status, 'released')
  assertEquals(relRow.insyt_id, 'ia') // inherits the hold's Insyt
  await rejects(record(f.pg, { kind: 'hold_released', amount: 900, related: hold }), 'already_released')
  // Only a hold of the same creator can be released.
  const refund = await record(f.pg, { kind: 'refund', amount: 10, purchase: f.pa })
  await rejects(record(f.pg, { kind: 'hold_released', amount: 10, related: refund }), 'related_invalid')
  const holdB = await record(f.pg, { creator: B, kind: 'hold', amount: 5 })
  await rejects(record(f.pg, { kind: 'hold_released', amount: 5, related: holdB }), 'related_invalid')
  await rejects(record(f.pg, { kind: 'hold_released', amount: 5 }), 'related_invalid')
})

