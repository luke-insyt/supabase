// GET-459 — purchases_rn_session_uidx, checked on a real Postgres (PGlite, in-process; no
// Docker, no network, no secrets).
//
// Runs 20261123130000_get459_purchases_rn_session_unique.sql on a stand-in purchases table
// and asserts:
//   - a second RN-webhook row (stripe_blob null) for the same session is a 23505;
//   - n8n's twin row (same session, stripe_blob set) is still allowed, before or after;
//   - rows without a session ('' or null) are left alone;
//   - existing duplicates make the migration fail with the named sessions, not a bare
//     23505 — and nothing is deleted;
//   - the migration is idempotent (runs twice).
//
// Run (from the repo root):  deno test -A supabase/tests/get459_purchases_rn_session_unique_test.ts
// Side-by-side checkout:     DENO_NO_PACKAGE_JSON=1 deno test -A supabase/tests/get459_purchases_rn_session_unique_test.ts
import { assertEquals, assertMatch, assertRejects } from 'jsr:@std/assert@1'
import { PGlite } from 'npm:@electric-sql/pglite@0.2.17'

const migration = await Deno.readTextFile(
  new URL('../migrations/20261123130000_get459_purchases_rn_session_unique.sql', import.meta.url),
)

const STAND_IN = `
create table public.purchases (
  id bigint generated by default as identity primary key,
  insyt_id text,
  buyer_email text,
  stripe_session_id text,
  stripe_blob json);
`

async function db(seed = '') {
  const pg = new PGlite()
  await pg.exec(STAND_IN)
  if (seed) await pg.exec(seed)
  return pg
}

const rn = (pg: PGlite, session: string | null) =>
  pg.query(`insert into public.purchases (insyt_id, stripe_session_id) values ('s', $1)`, [session])
const n8n = (pg: PGlite, session: string) =>
  pg.query(`insert into public.purchases (insyt_id, stripe_session_id, stripe_blob) values ('s', $1, '{"object":{}}')`, [session])
const count = async (pg: PGlite) => (await pg.query<{ n: number }>(`select count(*)::int as n from public.purchases`)).rows[0].n

Deno.test('a second RN row for one checkout is a 23505', async () => {
  const pg = await db()
  await pg.exec(migration)
  await rn(pg, 'cs_1')
  const err = await assertRejects(() => rn(pg, 'cs_1'))
  assertEquals((err as { code?: string }).code, '23505')
  await rn(pg, 'cs_2') // another checkout is fine
  assertEquals(await count(pg), 2)
})

Deno.test("n8n's twin (stripe_blob set) is allowed before and after the RN row", async () => {
  const pg = await db()
  await pg.exec(migration)
  await n8n(pg, 'cs_1')
  await rn(pg, 'cs_1')
  await n8n(pg, 'cs_1')
  assertEquals(await count(pg), 3)
})

Deno.test("rows without a session ('' or null) are outside the index", async () => {
  const pg = await db()
  await pg.exec(migration)
  for (const s of ['', '', null, null]) await rn(pg, s)
  assertEquals(await count(pg), 4)
})

Deno.test('existing duplicates: the migration fails naming the session, and deletes nothing', async () => {
  const pg = await db(`
    insert into public.purchases (insyt_id, stripe_session_id) values ('s', 'cs_dup'), ('s', 'cs_dup'), ('s', 'cs_ok');
    insert into public.purchases (insyt_id, stripe_session_id, stripe_blob) values ('s', 'cs_ok', '{}');`)
  const err = await assertRejects(() => pg.exec(migration))
  assertMatch(String((err as Error).message), /duplicate RN-webhook rows.*cs_dup \(2 rows\)/)
  await pg.exec('rollback') // the failed explicit transaction
  assertEquals(await count(pg), 4)
  const idx = await pg.query(`select 1 from pg_indexes where indexname = 'purchases_rn_session_uidx'`)
  assertEquals(idx.rows.length, 0)
})

Deno.test('the migration is idempotent', async () => {
  const pg = await db()
  await pg.exec(migration)
  await pg.exec(migration)
  await rn(pg, 'cs_1')
  await assertRejects(() => rn(pg, 'cs_1'))
})
