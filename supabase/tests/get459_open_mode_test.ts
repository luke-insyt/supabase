// GET-459 — "Open for everyone" migration, checked on a real Postgres (PGlite, in-process;
// no Docker, no network, no secrets).
//
// Runs 20261121120000_get459_open_mode.sql on a minimal stand-in of the tables it touches
// (inquiries + its updated_at trigger, insyts + GET-73's touch trigger, purchases), with rows
// that exist BEFORE the migration, then asserts:
//   - backfill: is_exclusive → exclusive / timed, drafts too; inquiries.updated_at untouched;
//     released_at = coalesce(published_at, updated_at) on public inquiry insyts only, and
//     insyts.updated_at untouched (the get277 feed-sort defect);
//   - the sync trigger: an old insert with is_exclusive=true → exclusive; a new insert with a
//     mode derives is_exclusive; an update of either column syncs the other; a draft with no
//     mode stays null; an old client's publish of a mode-less draft maps is_exclusive;
//   - the checks: a non-draft without a mode, or an unknown mode, is a check violation; an
//     archived mode-less draft is allowed (the account-deletion wipe);
//   - release_inquiry_insyt: releases at coalesce(release_price_cents, price_eur); a second
//     call returns no row; unpublished, public and non-inquiry rows are skipped;
//   - EXECUTE on the RPC is service_role only; the new columns aren't granted to browser roles;
//   - the migration is idempotent (runs twice).
//
// Run (from the repo root):  deno test -A supabase/tests/get459_open_mode_test.ts
// Side-by-side checkout:     DENO_NO_PACKAGE_JSON=1 deno test -A supabase/tests/get459_open_mode_test.ts
// No local Deno?             npx -y deno@2.1.4 test -A --node-modules-dir=none supabase/tests/get459_open_mode_test.ts
import { assert, assertEquals, assertRejects } from 'jsr:@std/assert@1'
import { PGlite } from 'npm:@electric-sql/pglite@0.2.17'

const migration = await Deno.readTextFile(
  new URL('../migrations/20261121120000_get459_open_mode.sql', import.meta.url),
)

// The columns the migration reads, plus the two triggers it suppresses around its backfills.
const STAND_IN = `
create role anon; create role authenticated; create role service_role;
create table public.inquiries (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'draft',
  is_exclusive boolean not null default false,
  published_at timestamptz,
  updated_at timestamptz not null default now());
create or replace function public.inquiries_before_write() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end; $$;
create trigger inquiries_before_write before insert or update on public.inquiries
  for each row execute function public.inquiries_before_write();
create table public.insyts (
  id uuid primary key default gen_random_uuid(),
  insyt_id character varying,
  price_eur integer not null,
  status character varying default 'review',
  is_hidden boolean default false,
  visibility text not null default 'public',
  private_until timestamptz,
  inquiry_proposal_id uuid,
  published_at timestamptz,
  updated_at timestamptz default now());
create or replace function public.touch_insyts_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end; $$;
create trigger touch_insyts_updated_at before update on public.insyts
  for each row execute function public.touch_insyts_updated_at();
create table public.purchases (id bigint generated by default as identity primary key, insyt_id text);
-- Supabase's default privileges: every NEW function in public is granted to the API roles.
-- Without this the EXECUTE revoke check below could never fail.
alter default privileges in schema public grant execute on functions to anon, authenticated;
`

const OLD = '2026-01-01T00:00:00Z'
const PUBLISHED = '2026-02-01T00:00:00Z'

type Fixture = {
  pg: PGlite
  legacy: { exclusive: string; timed: string; draft: string }
  flipped: string // a GET-331 stage-5 flip: public inquiry insyt
  flippedNoPublish: string // same, without published_at
  plain: string // a normal public insyt (no inquiry)
}

async function db(): Promise<Fixture> {
  const pg = new PGlite()
  await pg.exec(STAND_IN)
  const inq = async (status: string, isExclusive: boolean) =>
    (await pg.query<{ id: string }>(
      `insert into public.inquiries (status, is_exclusive) values ($1, $2) returning id`,
      [status, isExclusive],
    )).rows[0].id
  const legacy = {
    exclusive: await inq('open', true),
    timed: await inq('in_progress', false),
    draft: await inq('draft', false),
  }
  await pg.exec(`alter table public.inquiries disable trigger inquiries_before_write;
                 update public.inquiries set updated_at = '${OLD}';
                 alter table public.inquiries enable trigger inquiries_before_write;`)
  const insyt = async (cols: Record<string, unknown>) => {
    const keys = Object.keys(cols)
    return (await pg.query<{ id: string }>(
      `insert into public.insyts (${keys.join(', ')}) values (${keys.map((_, i) => `$${i + 1}`).join(', ')}) returning id`,
      Object.values(cols),
    )).rows[0].id
  }
  const flipped = await insyt({ insyt_id: 'flipped', price_eur: 900, status: 'live', inquiry_proposal_id: crypto.randomUUID(), published_at: PUBLISHED, updated_at: OLD })
  const flippedNoPublish = await insyt({ insyt_id: 'flipped2', price_eur: 900, status: 'live', inquiry_proposal_id: crypto.randomUUID(), updated_at: OLD })
  const plain = await insyt({ insyt_id: 'plain', price_eur: 500, status: 'live', published_at: PUBLISHED, updated_at: OLD })
  await pg.exec(migration)
  return { pg, legacy, flipped, flippedNoPublish, plain }
}

type Mode = { access_mode: string | null; is_exclusive: boolean }
const mode = async (pg: PGlite, id: string): Promise<Mode> =>
  (await pg.query<Mode>(`select access_mode, is_exclusive from public.inquiries where id = $1`, [id])).rows[0]

const insertInquiry = async (pg: PGlite, cols: Record<string, unknown>) => {
  const keys = Object.keys(cols)
  return (await pg.query<{ id: string }>(
    `insert into public.inquiries (${keys.join(', ')}) values (${keys.map((_, i) => `$${i + 1}`).join(', ')}) returning id`,
    Object.values(cols),
  )).rows[0].id
}

// A delivered (private, published) inquiry insyt, as submit-create-insyt writes it.
const delivered = async (pg: PGlite, releasePriceCents: number | null, status = 'live') =>
  (await pg.query<{ id: string }>(
    `insert into public.insyts (insyt_id, price_eur, status, visibility, private_until, inquiry_proposal_id, release_price_cents)
     values ('d-' || gen_random_uuid(), 2500, $1, 'private', 'infinity', gen_random_uuid(), $2) returning id`,
    [status, releasePriceCents],
  )).rows[0].id

type Released = { id: string; insyt_id: string; price_eur: number; is_hidden: boolean; inquiry_proposal_id: string }
const release = async (pg: PGlite, id: string) =>
  (await pg.query<Released>(`select * from public.release_inquiry_insyt($1)`, [id])).rows

Deno.test('backfill: every existing inquiry gets a mode, drafts too, and keeps its updated_at', async () => {
  const f = await db()
  assertEquals(await mode(f.pg, f.legacy.exclusive), { access_mode: 'exclusive', is_exclusive: true })
  assertEquals(await mode(f.pg, f.legacy.timed), { access_mode: 'timed', is_exclusive: false })
  assertEquals(await mode(f.pg, f.legacy.draft), { access_mode: 'timed', is_exclusive: false })
  const stamps = (await f.pg.query<{ u: Date }>(`select updated_at as u from public.inquiries`)).rows
  assert(stamps.every((r) => r.u.toISOString() === new Date(OLD).toISOString()))
})

Deno.test('backfill: released_at on public inquiry insyts only, and insyts.updated_at untouched', async () => {
  const f = await db()
  const rows = (await f.pg.query<{ id: string; released_at: Date | null; updated_at: Date }>(
    `select id, released_at, updated_at from public.insyts`,
  )).rows
  const by = Object.fromEntries(rows.map((r) => [r.id, r]))
  assertEquals(by[f.flipped].released_at?.toISOString(), new Date(PUBLISHED).toISOString())
  assertEquals(by[f.flippedNoPublish].released_at?.toISOString(), new Date(OLD).toISOString())
  assertEquals(by[f.plain].released_at, null)
  assert(rows.every((r) => r.updated_at.toISOString() === new Date(OLD).toISOString()))
})

Deno.test('trigger INSERT: an old client with is_exclusive=true gets exclusive; a new draft keeps a null mode', async () => {
  const f = await db()
  assertEquals(await mode(f.pg, await insertInquiry(f.pg, { status: 'draft', is_exclusive: true })), { access_mode: 'exclusive', is_exclusive: true })
  assertEquals(await mode(f.pg, await insertInquiry(f.pg, { status: 'open', is_exclusive: true })), { access_mode: 'exclusive', is_exclusive: true })
  assertEquals(await mode(f.pg, await insertInquiry(f.pg, { status: 'draft' })), { access_mode: null, is_exclusive: false })
  assertEquals(await mode(f.pg, await insertInquiry(f.pg, { status: 'draft', is_exclusive: false })), { access_mode: null, is_exclusive: false })
})

Deno.test('trigger INSERT: a mode wins and derives is_exclusive', async () => {
  const f = await db()
  assertEquals(await mode(f.pg, await insertInquiry(f.pg, { status: 'draft', access_mode: 'open', is_exclusive: true })), { access_mode: 'open', is_exclusive: false })
  assertEquals(await mode(f.pg, await insertInquiry(f.pg, { status: 'open', access_mode: 'exclusive' })), { access_mode: 'exclusive', is_exclusive: true })
  assertEquals(await mode(f.pg, await insertInquiry(f.pg, { status: 'open', access_mode: 'timed' })), { access_mode: 'timed', is_exclusive: false })
})

Deno.test('trigger UPDATE: changing either column syncs the other; access_mode wins when both change', async () => {
  const f = await db()
  const id = f.legacy.timed
  await f.pg.query(`update public.inquiries set access_mode = 'exclusive' where id = $1`, [id])
  assertEquals(await mode(f.pg, id), { access_mode: 'exclusive', is_exclusive: true })
  await f.pg.query(`update public.inquiries set access_mode = 'open' where id = $1`, [id])
  assertEquals(await mode(f.pg, id), { access_mode: 'open', is_exclusive: false })
  await f.pg.query(`update public.inquiries set is_exclusive = true where id = $1`, [id])
  assertEquals(await mode(f.pg, id), { access_mode: 'exclusive', is_exclusive: true })
  await f.pg.query(`update public.inquiries set is_exclusive = false where id = $1`, [id])
  assertEquals(await mode(f.pg, id), { access_mode: 'timed', is_exclusive: false })
  await f.pg.query(`update public.inquiries set access_mode = 'open', is_exclusive = true where id = $1`, [id])
  assertEquals(await mode(f.pg, id), { access_mode: 'open', is_exclusive: false })
  await f.pg.query(`update public.inquiries set status = 'completed' where id = $1`, [id])
  assertEquals(await mode(f.pg, id), { access_mode: 'open', is_exclusive: false })
})

Deno.test("trigger UPDATE: an old client's publish of a mode-less draft maps is_exclusive (S1-AC5)", async () => {
  const f = await db()
  const timed = await insertInquiry(f.pg, { status: 'draft' })
  await f.pg.query(`update public.inquiries set status = 'open' where id = $1`, [timed])
  assertEquals(await mode(f.pg, timed), { access_mode: 'timed', is_exclusive: false })
  // A draft the new server saved with a mode publishes with that mode.
  const open = await insertInquiry(f.pg, { status: 'draft', access_mode: 'open' })
  await f.pg.query(`update public.inquiries set status = 'open' where id = $1`, [open])
  assertEquals(await mode(f.pg, open), { access_mode: 'open', is_exclusive: false })
})

Deno.test('checks: a non-draft without a mode or with an unknown mode is refused; an archived mode-less draft is not', async () => {
  const f = await db()
  await assertRejects(
    () => f.pg.query(`update public.inquiries set access_mode = null where id = $1`, [f.legacy.exclusive]),
    Error,
    'inquiries_access_mode_required',
  )
  await assertRejects(
    () => f.pg.query(`update public.inquiries set access_mode = 'public' where id = $1`, [f.legacy.exclusive]),
    Error,
    'inquiries_access_mode_check',
  )
  await assertRejects(
    () => insertInquiry(f.pg, { status: 'open', access_mode: 'forever' }),
    Error,
    'inquiries_access_mode_check',
  )
  // The check itself, without the trigger's old-client mapping (it backs every writer).
  await f.pg.exec(`alter table public.inquiries disable trigger inquiries_access_mode_sync`)
  await assertRejects(() => insertInquiry(f.pg, { status: 'open' }), Error, 'inquiries_access_mode_required')
  await f.pg.exec(`alter table public.inquiries enable trigger inquiries_access_mode_sync`)
  const draft = await insertInquiry(f.pg, { status: 'draft' })
  await f.pg.query(`update public.inquiries set status = 'archived' where id = $1`, [draft])
  assertEquals(await mode(f.pg, draft), { access_mode: null, is_exclusive: false })
})

Deno.test('release: open mode goes public at €0 and stamps released_at + published_at; a second call returns no row', async () => {
  const f = await db()
  const id = await delivered(f.pg, 0)
  const first = await release(f.pg, id)
  assertEquals(first.length, 1)
  assertEquals(first[0].id, id)
  assertEquals(first[0].price_eur, 0)
  assertEquals(first[0].is_hidden, false)
  assert(first[0].insyt_id.startsWith('d-'))
  assert(first[0].inquiry_proposal_id)
  const row = (await f.pg.query<{ visibility: string; released_at: Date | null; published_at: Date | null; price_eur: number }>(
    `select visibility, released_at, published_at, price_eur from public.insyts where id = $1`, [id],
  )).rows[0]
  assertEquals(row.visibility, 'public')
  assert(row.released_at && row.published_at)
  assertEquals(row.price_eur, 0)
  assertEquals((await release(f.pg, id)).length, 0)
})

Deno.test("release: a null release_price_cents keeps the Insyter's price (timed)", async () => {
  const f = await db()
  const id = await delivered(f.pg, null)
  assertEquals((await release(f.pg, id))[0].price_eur, 2500)
})

Deno.test('release: skips unpublished, already-public, already-released and non-inquiry rows', async () => {
  const f = await db()
  const draft = await delivered(f.pg, 0, 'draft')
  assertEquals((await release(f.pg, draft)).length, 0)
  const unpublished = await delivered(f.pg, 0, 'unpublished')
  assertEquals((await release(f.pg, unpublished)).length, 0)
  assertEquals((await release(f.pg, f.flipped)).length, 0)
  assertEquals((await release(f.pg, f.plain)).length, 0)
  const notInquiry = (await f.pg.query<{ id: string }>(
    `insert into public.insyts (price_eur, status, visibility) values (100, 'live', 'private') returning id`,
  )).rows[0].id
  assertEquals((await release(f.pg, notInquiry)).length, 0)
  const unchanged = (await f.pg.query<{ n: number }>(
    `select count(*)::int as n from public.insyts where id = any($1) and visibility = 'private' and released_at is null`,
    [[draft, unpublished, notInquiry]],
  )).rows[0].n
  assertEquals(unchanged, 3)
})

Deno.test('grants: the RPC is service_role only; the trigger function is callable by no API role', async () => {
  const f = await db()
  const can = async (role: string, fn: string) =>
    (await f.pg.query<{ r: boolean }>(`select has_function_privilege($1, $2, 'execute') as r`, [role, fn])).rows[0].r
  for (const role of ['anon', 'authenticated']) {
    assertEquals(await can(role, 'public.release_inquiry_insyt(uuid)'), false)
    assertEquals(await can(role, 'public.inquiries_access_mode_sync()'), false)
  }
  assertEquals(await can('service_role', 'public.release_inquiry_insyt(uuid)'), true)
  const definer = (await f.pg.query<{ d: boolean }>(
    `select prosecdef as d from pg_proc where proname = 'release_inquiry_insyt'`,
  )).rows[0].d
  assertEquals(definer, true)
})

Deno.test('the partial index exists and the migration is idempotent', async () => {
  const f = await db()
  await f.pg.exec(migration)
  const idx = (await f.pg.query<{ def: string }>(
    `select indexdef as def from pg_indexes where indexname = 'insyts_inquiry_release_idx'`,
  )).rows[0].def
  assert(idx.includes('(visibility, released_at)') && idx.includes('inquiry_proposal_id IS NOT NULL'))
  assertEquals(await mode(f.pg, f.legacy.exclusive), { access_mode: 'exclusive', is_exclusive: true })
  const triggers = (await f.pg.query<{ n: number }>(
    `select count(*)::int as n from pg_trigger where tgname = 'inquiries_access_mode_sync'`,
  )).rows[0].n
  assertEquals(triggers, 1)
  // Both suppressed triggers are back on.
  const disabled = (await f.pg.query<{ n: number }>(
    `select count(*)::int as n from pg_trigger
      where tgname in ('inquiries_before_write', 'touch_insyts_updated_at') and tgenabled = 'D'`,
  )).rows[0].n
  assertEquals(disabled, 0)
})
