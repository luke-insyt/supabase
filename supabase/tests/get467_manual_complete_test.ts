// GET-467 — "Mark as complete" migration, checked on a real Postgres (PGlite, in-process;
// no Docker, no network, no secrets).
//
// Runs 20261126190000_get467_manual_complete.sql on a minimal stand-in of the tables it
// touches, then asserts inquiry_close_by_requester and inquiry_delivery_bought:
//   - not_found for a missing inquiry and for another user; already on a completed inquiry;
//   - refusals: draft / archived / moderated → refused/status; nothing delivered →
//     refused/nothing_delivered; a delivering proposal → delivering;
//   - the close: status completed + closed_by_requester_at; submitted and accepted →
//     cancelled/inquiry_closed; delivered-unbought → cancelled/inquiry_closed_delivered; bought
//     stays delivered; declined, withdrawn and already-cancelled proposals are untouched (S2-AC2);
//   - bought: under a different email while private counts; under the requester's email after
//     release counts; another user's purchase after release doesn't;
//   - the result JSON (delivered, bought, cancelled[] with `was`, wanted);
//   - EXECUTE is service_role only; the migration is idempotent.
//
// The P0467 race is simulated here on one connection (a test-only trigger claims a delivery
// mid-close); the two-connection version is get467_close_race_live_test.ts (needs SUPABASE_DB_URL).
//
// Run (from the repo root):  deno test -A supabase/tests/get467_manual_complete_test.ts
// Side-by-side checkout:     DENO_NO_PACKAGE_JSON=1 deno test -A supabase/tests/get467_manual_complete_test.ts
import { assert, assertEquals } from 'jsr:@std/assert@1'
import { PGlite } from 'npm:@electric-sql/pglite@0.2.17'

const migration = await Deno.readTextFile(
  new URL('../migrations/20261126190000_get467_manual_complete.sql', import.meta.url),
)

const STAND_IN = `
create role anon; create role authenticated; create role service_role;
create table public.users (auth_user_id uuid primary key, email text);
create table public.inquiries (
  id uuid primary key default gen_random_uuid(),
  requester_auth_user_id uuid,
  status text not null default 'draft',
  insyts_wanted integer,
  moderated_at timestamptz,
  updated_at timestamptz not null default now());
create table public.insyts (
  id uuid primary key default gen_random_uuid(),
  insyt_id character varying,
  visibility text not null default 'private',
  released_at timestamptz);
create table public.inquiry_proposals (
  id uuid primary key default gen_random_uuid(),
  inquiry_id uuid not null references public.inquiries (id),
  insyter_auth_user_id uuid,
  status text not null default 'submitted',
  cancel_reason text,
  insyt_id uuid references public.insyts (id));
create table public.purchases (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  buyer_email text,
  insyt_id text);
alter default privileges in schema public grant execute on functions to anon, authenticated;
`

const REQ = '00000000-0000-0000-0000-00000000000a'
const OTHER = '00000000-0000-0000-0000-00000000000b'
const INS = (n: number) => `00000000-0000-0000-0000-0000000001${String(n).padStart(2, '0')}`

async function db(): Promise<PGlite> {
  const pg = new PGlite()
  await pg.exec(STAND_IN)
  await pg.exec(migration)
  await pg.query(`insert into public.users values ($1, 'req@example.com'), ($2, 'other@example.com')`, [REQ, OTHER])
  return pg
}

async function inquiry(pg: PGlite, status = 'in_progress', extra: { moderated?: boolean; wanted?: number | null } = {}) {
  return (
    await pg.query<{ id: string }>(
      `insert into public.inquiries (requester_auth_user_id, status, insyts_wanted, moderated_at)
       values ($1, $2, $3, $4) returning id`,
      [REQ, status, extra.wanted === undefined ? 3 : extra.wanted, extra.moderated ? new Date().toISOString() : null],
    )
  ).rows[0].id
}

async function insyt(pg: PGlite, slug: string, releasedAt: string | null = null) {
  return (
    await pg.query<{ id: string }>(
      `insert into public.insyts (insyt_id, visibility, released_at) values ($1, $2, $3) returning id`,
      [slug, releasedAt ? 'public' : 'private', releasedAt],
    )
  ).rows[0].id
}

async function proposal(pg: PGlite, inq: string, insyter: string, status: string, insytId: string | null = null, cancelReason: string | null = null) {
  return (
    await pg.query<{ id: string }>(
      `insert into public.inquiry_proposals (inquiry_id, insyter_auth_user_id, status, insyt_id, cancel_reason)
       values ($1, $2, $3, $4, $5) returning id`,
      [inq, insyter, status, insytId, cancelReason],
    )
  ).rows[0].id
}

async function buy(pg: PGlite, slug: string, email: string, at: string) {
  await pg.query(`insert into public.purchases (buyer_email, insyt_id, created_at) values ($1, $2, $3)`, [email, slug, at])
}

type CloseResult = {
  result: string
  reason?: string
  delivered?: number
  bought?: number
  wanted?: number | null
  cancelled?: { proposal_id: string; insyter_auth_user_id: string; was: string; insyt_id: string | null }[]
}

async function close(pg: PGlite, inq: string, requester = REQ): Promise<CloseResult> {
  return (await pg.query<{ r: CloseResult }>(`select public.inquiry_close_by_requester($1, $2) as r`, [inq, requester])).rows[0].r
}

const row = async (pg: PGlite, id: string) =>
  (await pg.query<{ status: string; cancel_reason: string | null }>(`select status, cancel_reason from public.inquiry_proposals where id = $1`, [id])).rows[0]
const inq = async (pg: PGlite, id: string) =>
  (await pg.query<{ status: string; closed: string | null }>(`select status, closed_by_requester_at as closed from public.inquiries where id = $1`, [id])).rows[0]

Deno.test('not_found: a missing inquiry and another user', async () => {
  const pg = await db()
  const i = await inquiry(pg)
  await proposal(pg, i, INS(1), 'delivered', await insyt(pg, 'a'))
  assertEquals((await close(pg, '00000000-0000-0000-0000-0000000000ff')).result, 'not_found')
  assertEquals((await close(pg, i, OTHER)).result, 'not_found')
  assertEquals((await inq(pg, i)).status, 'in_progress')
})

Deno.test('already: a completed inquiry changes nothing', async () => {
  const pg = await db()
  const i = await inquiry(pg, 'completed')
  const p = await proposal(pg, i, INS(1), 'submitted')
  assertEquals((await close(pg, i)).result, 'already')
  assertEquals((await row(pg, p)).status, 'submitted')
  assertEquals((await inq(pg, i)).closed, null)
})

Deno.test('refused: draft, archived and moderated → status; nothing delivered → nothing_delivered', async () => {
  const pg = await db()
  for (const status of ['draft', 'archived']) {
    const i = await inquiry(pg, status)
    await proposal(pg, i, INS(1), 'delivered', await insyt(pg, `s-${status}`))
    assertEquals(await close(pg, i), { result: 'refused', reason: 'status' })
  }
  const m = await inquiry(pg, 'unpublished', { moderated: true })
  await proposal(pg, m, INS(1), 'delivered', await insyt(pg, 's-mod'))
  assertEquals(await close(pg, m), { result: 'refused', reason: 'status' })

  const n = await inquiry(pg, 'in_progress')
  await proposal(pg, n, INS(1), 'accepted')
  assertEquals(await close(pg, n), { result: 'refused', reason: 'nothing_delivered' })
  assertEquals((await inq(pg, n)).status, 'in_progress')
})

Deno.test('delivering: a proposal being published refuses the close', async () => {
  const pg = await db()
  const i = await inquiry(pg)
  await proposal(pg, i, INS(1), 'delivered', await insyt(pg, 'a'))
  const d = await proposal(pg, i, INS(2), 'delivering')
  assertEquals((await close(pg, i)).result, 'delivering')
  assertEquals((await row(pg, d)).status, 'delivering')
  assertEquals((await inq(pg, i)).status, 'in_progress')
})

Deno.test('the close: mixed proposals, untouched finished ones, and the result JSON', async () => {
  const pg = await db()
  const i = await inquiry(pg, 'in_progress', { wanted: 4 })
  const boughtInsyt = await insyt(pg, 'bought')
  const unboughtInsyt = await insyt(pg, 'unbought')
  await buy(pg, 'bought', 'req@example.com', '2026-01-01T00:00:00Z')
  const bought = await proposal(pg, i, INS(1), 'delivered', boughtInsyt)
  const unbought = await proposal(pg, i, INS(2), 'delivered', unboughtInsyt)
  const accepted = await proposal(pg, i, INS(3), 'accepted')
  const submitted = await proposal(pg, i, INS(4), 'submitted')
  const declined = await proposal(pg, i, INS(5), 'declined')
  const withdrawn = await proposal(pg, i, INS(6), 'withdrawn')
  const earlier = await proposal(pg, i, INS(7), 'cancelled', null, 'requester_cancelled')

  const r = await close(pg, i)
  assertEquals(r.result, 'ok')
  assertEquals(r.delivered, 2)
  assertEquals(r.bought, 1)
  assertEquals(r.wanted, 4)
  const byId = new Map(r.cancelled!.map((c) => [c.proposal_id, c]))
  assertEquals(byId.size, 3)
  assertEquals(byId.get(accepted)?.was, 'accepted')
  assertEquals(byId.get(submitted)?.was, 'submitted')
  assertEquals(byId.get(unbought)?.was, 'delivered')
  assertEquals(byId.get(unbought)?.insyt_id, unboughtInsyt)
  assertEquals(byId.get(unbought)?.insyter_auth_user_id, INS(2))

  assertEquals(await row(pg, bought), { status: 'delivered', cancel_reason: null })
  assertEquals(await row(pg, unbought), { status: 'cancelled', cancel_reason: 'inquiry_closed_delivered' })
  assertEquals(await row(pg, accepted), { status: 'cancelled', cancel_reason: 'inquiry_closed' })
  assertEquals(await row(pg, submitted), { status: 'cancelled', cancel_reason: 'inquiry_closed' })
  assertEquals(await row(pg, declined), { status: 'declined', cancel_reason: null })
  assertEquals(await row(pg, withdrawn), { status: 'withdrawn', cancel_reason: null })
  assertEquals(await row(pg, earlier), { status: 'cancelled', cancel_reason: 'requester_cancelled' })

  const after = await inq(pg, i)
  assertEquals(after.status, 'completed')
  assert(after.closed !== null)

  // A second call is `already` and changes nothing.
  assertEquals((await close(pg, i)).result, 'already')
})

Deno.test('the close works from unpublished, and with no capacity (wanted null)', async () => {
  const pg = await db()
  const i = await inquiry(pg, 'unpublished', { wanted: null })
  await proposal(pg, i, INS(1), 'delivered', await insyt(pg, 'a'))
  const r = await close(pg, i)
  assertEquals(r.result, 'ok')
  assertEquals(r.wanted, null)
  assertEquals(r.bought, 0)
  assertEquals((await inq(pg, i)).status, 'completed')
})

Deno.test('bought: private purchase under another email counts; after release only the requester email counts', async () => {
  const pg = await db()
  const i = await inquiry(pg)
  const privateBuy = await insyt(pg, 'private-buy', '2026-03-01T00:00:00Z')
  await buy(pg, 'private-buy', 'old-address@example.com', '2026-02-01T00:00:00Z') // before release
  const ownAfter = await insyt(pg, 'own-after', '2026-03-01T00:00:00Z')
  await buy(pg, 'own-after', 'REQ@example.com', '2026-04-01T00:00:00Z') // after release, case differs
  const strangerAfter = await insyt(pg, 'stranger-after', '2026-03-01T00:00:00Z')
  await buy(pg, 'stranger-after', 'other@example.com', '2026-04-01T00:00:00Z') // a member of the public

  const bought = async (id: string) =>
    (await pg.query<{ b: boolean }>(`select public.inquiry_delivery_bought($1, $2) as b`, [id, REQ])).rows[0].b
  assertEquals(await bought(privateBuy), true)
  assertEquals(await bought(ownAfter), true)
  assertEquals(await bought(strangerAfter), false)

  const a = await proposal(pg, i, INS(1), 'delivered', privateBuy)
  const b = await proposal(pg, i, INS(2), 'delivered', ownAfter)
  const c = await proposal(pg, i, INS(3), 'delivered', strangerAfter)
  const r = await close(pg, i)
  assertEquals(r.bought, 2)
  assertEquals((await row(pg, a)).status, 'delivered')
  assertEquals((await row(pg, b)).status, 'delivered')
  assertEquals(await row(pg, c), { status: 'cancelled', cancel_reason: 'inquiry_closed_delivered' })
})

// The race, simulated on one connection: a test-only trigger claims a delivery (accepted →
// delivering) the moment the close writes the inquiry, i.e. after the refusal checks passed,
// as a concurrent claimDelivery committing mid-close would. The shipped function's step-4
// `accepted` update then skips that row and its step-5 re-check must abort the whole close.
Deno.test('race: a delivery claimed mid-close aborts with P0467 and changes nothing', async () => {
  const pg = await db()
  const i = await inquiry(pg)
  const delivered = await proposal(pg, i, INS(1), 'delivered', await insyt(pg, 'a'))
  const accepted = await proposal(pg, i, INS(2), 'accepted')
  const submitted = await proposal(pg, i, INS(3), 'submitted')
  await pg.exec(`
    create function public.test_claim_mid_close() returns trigger language plpgsql as $$
    begin
      if new.status = 'completed' and old.status <> 'completed' then
        update public.inquiry_proposals set status = 'delivering'
         where inquiry_id = new.id and status = 'accepted';
      end if;
      return new;
    end; $$;
    create trigger test_claim_mid_close after update on public.inquiries
      for each row execute function public.test_claim_mid_close();`)

  let code: string | undefined
  try {
    await close(pg, i)
  } catch (e) {
    code = (e as { code?: string }).code
  }
  assertEquals(code, 'P0467')
  assertEquals(await inq(pg, i), { status: 'in_progress', closed: null })
  assertEquals((await row(pg, delivered)).status, 'delivered')
  assertEquals((await row(pg, accepted)).status, 'accepted') // the claim rolled back with the close
  assertEquals((await row(pg, submitted)).status, 'submitted')
})

Deno.test('grants: both functions are service_role only', async () => {
  const pg = await db()
  const can = async (role: string, fn: string) =>
    (await pg.query<{ r: boolean }>(`select has_function_privilege($1, $2, 'execute') as r`, [role, fn])).rows[0].r
  for (const fn of ['public.inquiry_close_by_requester(uuid, uuid)', 'public.inquiry_delivery_bought(uuid, uuid)']) {
    assertEquals(await can('anon', fn), false, `${fn} anon`)
    assertEquals(await can('authenticated', fn), false, `${fn} authenticated`)
    assertEquals(await can('service_role', fn), true, `${fn} service_role`)
  }
})

