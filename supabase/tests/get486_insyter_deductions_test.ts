Deno.test('grants: the RPCs are service_role only; no API role reads the table; the trigger fn runs for nobody', async () => {
  const f = await db()
  const can = async (role: string, fn: string) =>
    (await f.pg.query<{ r: boolean }>(`select has_function_privilege($1, $2, 'execute') as r`, [role, fn])).rows[0].r
  const fns = [
    'public.record_insyter_deduction(uuid, uuid, text, bigint, text, bigint, uuid, text, text, uuid, text, text)',
    'public.insyter_deductions_for(uuid, integer, integer)',
    'public.create_payout_with_settlement(uuid, bigint, text, text, jsonb, uuid[])',
  ]
  for (const fn of fns) {
    assertEquals(await can('anon', fn), false, fn)
    assertEquals(await can('authenticated', fn), false, fn)
    assertEquals(await can('service_role', fn), true, fn)
  }
  for (const role of ['anon', 'authenticated', 'service_role']) {
    assertEquals(await can(role, 'public.insyter_deductions_immutable()'), false, role)
  }
  const tbl = async (role: string, priv: string) =>
    (await f.pg.query<{ r: boolean }>(`select has_table_privilege($1, 'public.insyter_deductions', $2) as r`, [role, priv])).rows[0].r
  for (const role of ['anon', 'authenticated']) {
    for (const priv of ['select', 'insert', 'update', 'delete']) assertEquals(await tbl(role, priv), false, `${role} ${priv}`)
  }
  assertEquals(await tbl('service_role', 'select'), true)
  for (const priv of ['insert', 'update', 'delete', 'truncate']) assertEquals(await tbl('service_role', priv), false, priv)
  // A real 42501 for a signed-in caller.
  await f.pg.exec('set role authenticated')
  try {
    await assertRejects(() => f.pg.query(`select * from public.insyter_deductions_for($1)`, [A]), Error, 'permission denied')
  } finally {
    await f.pg.exec('reset role')
  }
  const rls = (await f.pg.query<{ r: boolean }>(`select relrowsecurity as r from pg_class where oid = 'public.insyter_deductions'::regclass`)).rows[0].r
  assertEquals(rls, true)
})

